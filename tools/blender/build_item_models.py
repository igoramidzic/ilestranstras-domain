_image_cache = {}


def image(name, rgb, alpha=None, data=False):
    """Makes a packed Blender image from a (H, W, 3) array (row 0 = bottom).
    Identical pixels give back the same image, so shared textures are stored once."""
    h, w = rgb.shape[:2]
    px = np.ones((h, w, 4), np.float32)
    px[..., :3] = np.clip(rgb, 0.0, 1.0)
    if alpha is not None:
        px[..., 3] = alpha
    key = (hashlib.md5(px.tobytes()).hexdigest(), data)
    if key in _image_cache:
        return _image_cache[key]
    img = bpy.data.images.new(name, w, h, alpha=alpha is not None)
    if data:
        img.colorspace_settings.name = "Non-Color"
    img.pixels.foreach_set(px.ravel())
    _image_cache[key] = img
    path = os.path.join(_texture_dir, name + ".png")
    img.filepath_raw = path
    img.file_format = "PNG"
    img.save()
    img.filepath = path  # Made relative to the .blend when it's saved.
    return img


def use_texture_dir(path):
    """Starts a fresh texture folder for the next .blend."""
    global _texture_dir
    _texture_dir = path
    if os.path.isdir(path):
        for f in os.listdir(path):
            if f.endswith(".png") or f.endswith(".png.import"):
                os.remove(os.path.join(path, f))
    os.makedirs(path, exist_ok=True)


def gray_to_rgb(a):
    return np.dstack([a, a, a])


def material(name, color=(0.8, 0.8, 0.8), rough=0.5, metal=0.0, albedo=None, rough_map=None,
             metal_map=None, height=None, bump=1.0, alpha=None, double_sided=False,
             emit=None, emit_strength=0.0):
    """Principled material wired the way the glTF exporter understands:
    albedo -> Base Color (alpha via Round -> alpha clip), roughness in G and
    metallic in B of one packed image, height -> generated normal map."""
    mat = bpy.data.materials.new(name)
    if mat.node_tree is None:  # Blender < 5 creates materials without nodes.
        mat.use_nodes = True
    nt = mat.node_tree
    bsdf = next(n for n in nt.nodes if n.type == "BSDF_PRINCIPLED")
    bsdf.inputs["Base Color"].default_value = (*color, 1.0)
    bsdf.inputs["Roughness"].default_value = rough
    bsdf.inputs["Metallic"].default_value = metal
    mat.diffuse_color = (*color, 1.0)
    mat.use_backface_culling = not double_sided

    x = -700
    if albedo is not None:
        tex = nt.nodes.new("ShaderNodeTexImage")
        tex.location = (x, 300)
        tex.image = image(name + "_albedo", albedo, alpha=alpha)
        nt.links.new(tex.outputs["Color"], bsdf.inputs["Base Color"])
        if alpha is not None:
            clip = nt.nodes.new("ShaderNodeMath")
            clip.operation = "ROUND"
            clip.location = (x + 300, 100)
            nt.links.new(tex.outputs["Alpha"], clip.inputs[0])
            nt.links.new(clip.outputs[0], bsdf.inputs["Alpha"])
            try:
                mat.surface_render_method = "DITHERED"
            except AttributeError:
                pass

    if rough_map is not None or metal_map is not None:
        r = rough_map if rough_map is not None else np.full(albedo.shape[:2], rough, np.float32)
        m = metal_map if metal_map is not None else np.full(r.shape, metal, np.float32)
        packed = np.dstack([np.ones_like(r), r, m])
        tex = nt.nodes.new("ShaderNodeTexImage")
        tex.location = (x, 0)
        tex.image = image(name + "_orm", packed, data=True)
        sep = nt.nodes.new("ShaderNodeSeparateColor")
        sep.location = (x + 300, -50)
        nt.links.new(tex.outputs["Color"], sep.inputs[0])
        nt.links.new(sep.outputs["Green"], bsdf.inputs["Roughness"])
        if metal_map is not None:
            nt.links.new(sep.outputs["Blue"], bsdf.inputs["Metallic"])

    if height is not None:
        tex = nt.nodes.new("ShaderNodeTexImage")
        tex.location = (x, -300)
        tex.image = image(name + "_normal", T.normal_map(height, bump), data=True)
        nmap = nt.nodes.new("ShaderNodeNormalMap")
        nmap.location = (x + 300, -300)
        nt.links.new(tex.outputs["Color"], nmap.inputs["Color"])
        nt.links.new(nmap.outputs["Normal"], bsdf.inputs["Normal"])

    if emit is not None:
        bsdf.inputs["Emission Color"].default_value = (*emit, 1.0)
        bsdf.inputs["Emission Strength"].default_value = emit_strength
    return mat


