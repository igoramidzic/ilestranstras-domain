"""Builds the detailed, textured models for the rolling field.

Run from the project root:
    /Applications/Blender.app/Contents/MacOS/Blender --background --factory-startup \\
        --python tools/blender/build_item_models.py

Writes (and OVERWRITES):
  assets/models/items/items.blend      every pick-up item, one object each
  assets/models/characters/hero.blend  the character who pushes the ball
  assets/textures/ground/grass_*.png   tiling lawn textures for the ground shader

Textures are generated by item_textures.py and saved as PNGs in a textures/
folder next to each .blend (the .blend references them; Godot imports them
directly). Each run deletes and rewrites those folders.

Item objects are named "<Kind>_<variant>", e.g. "Mug_Red", "Car_Blue". The game's
ItemCatalog picks a random variant of a kind by that prefix, so to add a variant
just add another object with the same prefix. Don't use "-" in names (Godot
treats "-col" etc. as import hints).

Conventions: 1 unit = 1 m, real-world sizes, Z up. The game rescales items, so
only proportions matter, but real sizes keep texture scale consistent.
"""

