def leaf_cards(name, anchors, size_range, mat, crown_center, crown_scale=(1, 1, 1), seed=0,
               outward=0.75, droop=0.0):
    """One quad per anchor, its stem end at the anchor, pointing outward.
    Normals bend toward 'outward from the crown' so the crown shades like a volume."""
    rng = np.random.default_rng(seed)
    verts, faces, normals = [], [], []
    c = Vector(crown_center)
    cs = Vector(crown_scale)
    for a in anchors:
        a = Vector(a)
        out = a - c
        out = Vector((out.x / cs.x, out.y / cs.y, out.z / cs.z))
        if out.length < 1e-4:
            out = Vector((0, 0, 1))
        out.normalize()
        direction = (out + Vector(rng.normal(size=3)) * 0.6 + Vector((0, 0, -droop))).normalized()
        side = direction.cross(Vector(rng.normal(size=3))).normalized()
        s = rng.uniform(*size_range)
        base = a - direction * s * 0.08
        corners = [base - side * s * 0.5, base + side * s * 0.5,
                   base + side * s * 0.5 + direction * s, base - side * s * 0.5 + direction * s]
        face_n = side.cross(direction).normalized()
        if face_n.dot(out) < 0:
            face_n = -face_n
        i = len(verts)
        verts.extend(corners)
        faces.append((i, i + 1, i + 2, i + 3))
        for corner in corners:
            radial = corner - c
            radial = Vector((radial.x / cs.x, radial.y / cs.y, radial.z / cs.z)).normalized()
            normals.append((radial * outward + face_n * (1 - outward)).normalized())
    obj = mesh_object(name, verts, faces)
    set_mats(obj, mat)
    uv_card(obj)
    obj.data.shade_smooth()
    obj.data.normals_split_custom_set_from_vertices([tuple(n) for n in normals])
    return obj


def points_in_ellipsoid(center, radii, count, rng, shell=0.65):
    pts = []
    while len(pts) < count:
        p = rng.uniform(-1, 1, 3)
        d = np.linalg.norm(p)
        if shell <= d <= 1.0:
            pts.append(np.array(center) + p * np.array(radii))
    return pts


