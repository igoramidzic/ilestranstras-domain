def save_png(path, rgb, data=False):
    h, w = rgb.shape[:2]
    img = bpy.data.images.new(os.path.basename(path), w, h)
    if data:
        img.colorspace_settings.name = "Non-Color"
    px = np.ones((h, w, 4), np.float32)
    px[..., :3] = np.clip(rgb, 0, 1)
    img.pixels.foreach_set(px.ravel())
    img.filepath_raw = path
    img.file_format = "PNG"
    img.save()
    bpy.data.images.remove(img)


def save(path):
    # Drop materials no object uses, and the texture files only they needed.
    for mat in list(bpy.data.materials):
        if mat.users == 0:
            bpy.data.materials.remove(mat)
    for img in list(bpy.data.images):
        if img.users == 0:
            if img.filepath_raw and os.path.exists(img.filepath_raw):
                os.remove(img.filepath_raw)
            bpy.data.images.remove(img)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    bpy.ops.wm.save_as_mainfile(filepath=path, compress=True)
    backup = path + "1"
    if os.path.exists(backup):
        os.remove(backup)  # Blender's .blend1 backup; we regenerate anyway.
    print("Saved", path)


