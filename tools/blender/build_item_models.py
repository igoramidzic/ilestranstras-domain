def make_die(M, mat, name):
    d = box((0.016, 0.016, 0.016), bevel_w=0.0028, segments=4)
    set_mats(d, mat)
    s = 0.0045
    faces = {
        (0, 0, 1): [(0, 0)],
        (0, 0, -1): [(-s, -s), (s, s), (-s, s), (s, -s), (-s, 0), (s, 0)],
        (1, 0, 0): [(-s, -s), (s, s)],
        (-1, 0, 0): [(-s, -s), (s, s), (-s, s), (s, -s), (0, 0)],
        (0, 1, 0): [(-s, -s), (s, s), (0, 0)],
        (0, -1, 0): [(-s, -s), (s, s), (-s, s), (s, -s)],
    }
    cutters = []
    for n, spots in faces.items():
        n = Vector(n)
        a = Vector((1, 0, 0)) if abs(n.x) < 0.5 else Vector((0, 1, 0))
        b = n.cross(a)
        for x, y in spots:
            pos = n * 0.0088 + a * x + b * y
            cutters.append(set_mats(sphere(0.0016, loc=tuple(pos), segments=16, rings=8), M["pip"]))
    cutter = join(cutters, name + "_cutter")
    m = d.modifiers.new("Pips", "BOOLEAN")
    m.object = cutter
    m.operation = "DIFFERENCE"
    m.material_mode = "TRANSFER"
    apply_mods(d)
    bpy.data.objects.remove(cutter)
    uv_box(d, 0.05)
    smooth(d, 30)
    return join([d], name)


