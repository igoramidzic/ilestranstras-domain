def make_tree(M, i):
    rng = np.random.default_rng(500 + i)
    verts = [(0, 0, 0)]
    radii = [0.3]
    edges = []

    def grow(parent, direction, length, radius, depth):
        cur = parent
        pos = Vector(verts[parent])
        d = Vector(direction).normalized()
        segs = 3
        tips = []
        chain = []
        for s in range(segs):
            d = (d + Vector(rng.normal(size=3)) * 0.18 + Vector((0, 0, 0.08))).normalized()
            pos = pos + d * (length / segs)
            verts.append(tuple(pos))
            radii.append(radius * (1.0 - 0.6 * (s + 1) / segs))
            edges.append((cur, len(verts) - 1))
            cur = len(verts) - 1
            chain.append(cur)
        tips.append(cur)
        if depth > 0:
            for k in range(rng.integers(2, 4)):
                a = rng.uniform(0, math.tau)
                nd = (d * 0.6 + Vector((math.cos(a), math.sin(a), 0.4)) * 0.8).normalized()
                start = chain[-1 - int(rng.integers(0, 2))]
                tips += grow(start, nd, length * 0.6, radius * 0.5, depth - 1)
        return tips

    # Trunk.
    trunk_h = 2.4
    for s in range(4):
        verts.append((rng.normal() * 0.05, rng.normal() * 0.05, (s + 1) * trunk_h / 4))
        radii.append(0.24 - s * 0.03)
        edges.append((len(verts) - 2, len(verts) - 1))
    top = len(verts) - 1
    for k in range(3):  # Root flare.
        a = k / 3 * math.tau + 0.4
        verts.append((math.cos(a) * 0.35, math.sin(a) * 0.35, -0.05))
        radii.append(0.12)
        edges.append((0, len(verts) - 1))
    tips = []
    for k in range(5):
        a = k / 5 * math.tau + rng.uniform(-0.3, 0.3)
        d = (math.cos(a), math.sin(a), 0.75)
        start = top - (k % 2)
        tips += grow(start, d, 2.6, 0.13, 1)
    wood = skin("trunk", verts, edges, radii, root=0, levels=1)
    part(wood, M["bark"], "box", angle=180, tile=1.0, grain="z")

    crown_center = (0.0, 0.0, trunk_h + 1.8)
    crown_r = (3.0, 3.0, 2.2)
    parts = [wood]
    for k, t in enumerate(tips[::2]):
        tv = Vector(verts[t])
        parts.append(foliage_blob("blob", tuple(tv + Vector((0, 0, 0.2))), (1.0, 1.0, 0.8), M["foliage"],
                                  600 + k, subdiv=2))
    anchors = []
    for t in tips:
        anchors += points_in_ellipsoid(verts[t], (1.2, 1.2, 0.95), 85, rng, shell=0.25)
    leaves = M["leaves" if i % 2 == 0 else "leaves_light"]
    parts.append(leaf_cards("crown", anchors, (0.55, 0.85), leaves, crown_center, crown_r, seed=700 + i,
                            outward=0.8))
    return join(parts, "Tree_%d" % (i + 1))


