def reset():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    _image_cache.clear()


def link(obj):
    bpy.context.scene.collection.objects.link(obj)
    return obj


def mesh_object(name, verts, faces, edges=()):
    me = bpy.data.meshes.new(name)
    me.from_pydata([tuple(v) for v in verts], list(edges), [tuple(f) for f in faces])
    me.validate()
    me.update()
    return link(bpy.data.objects.new(name, me))


def apply_transform(obj):
    obj.data.transform(obj.matrix_world)
    obj.matrix_world = Matrix.Identity(4)
    obj.data.update()


def apply_mods(obj):
    dg = bpy.context.evaluated_depsgraph_get()
    mesh = bpy.data.meshes.new_from_object(obj.evaluated_get(dg), preserve_all_data_layers=True, depsgraph=dg)
    old = obj.data
    obj.modifiers.clear()
    obj.data = mesh
    if old.users == 0:
        bpy.data.meshes.remove(old)


def active():
    return bpy.context.view_layer.objects.active


def box(size, loc=(0, 0, 0), rot=(0, 0, 0), bevel_w=0.0, segments=2):
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=loc, rotation=rot, scale=size)
    obj = active()
    apply_transform(obj)
    if bevel_w > 0:
        bevel(obj, bevel_w, segments)
    return obj


def cylinder(radius, depth, loc=(0, 0, 0), rot=(0, 0, 0), verts=32, top_radius=None, bevel_w=0.0):
    if top_radius is None:
        bpy.ops.mesh.primitive_cylinder_add(vertices=verts, radius=radius, depth=depth, location=loc, rotation=rot)
    else:
        bpy.ops.mesh.primitive_cone_add(vertices=verts, radius1=radius, radius2=top_radius, depth=depth,
                                        location=loc, rotation=rot)
    obj = active()
    apply_transform(obj)
    if bevel_w > 0:
        bevel(obj, bevel_w, 2)
    return obj


def sphere(radius, loc=(0, 0, 0), scale=(1, 1, 1), segments=32, rings=16):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=segments, ring_count=rings, radius=radius, location=loc,
                                         scale=scale)
    obj = active()
    apply_transform(obj)
    return obj


def ico(radius, subdiv=3, loc=(0, 0, 0), scale=(1, 1, 1)):
    bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=subdiv, radius=radius, location=loc, scale=scale)
    obj = active()
    apply_transform(obj)
    return obj


def bevel(obj, width, segments=2, angle=35):
    m = obj.modifiers.new("Bevel", "BEVEL")
    m.width = width
    m.segments = segments
    m.limit_method = "ANGLE"
    m.angle_limit = math.radians(angle)
    m.use_clamp_overlap = True
    apply_mods(obj)


def subsurf(obj, levels=1):
    m = obj.modifiers.new("Subsurf", "SUBSURF")
    m.levels = levels
    m.render_levels = levels
    apply_mods(obj)


def lathe(name, profile, steps=48):
    """Revolves a (radius, z) profile around Z. Start/end on the axis for a closed solid."""
    verts = [(r, 0.0, z) for r, z in profile]
    edges = [(i, i + 1) for i in range(len(verts) - 1)]
    obj = mesh_object(name, verts, [], edges)
    m = obj.modifiers.new("Screw", "SCREW")
    m.axis = "Z"
    m.angle = math.tau
    m.steps = steps
    m.render_steps = steps
    m.use_merge_vertices = True
    m.merge_threshold = 1e-5
    m.use_normal_calculate = True
    apply_mods(obj)
    recalc_normals(obj)
    return obj


def recalc_normals(obj):
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(obj.data)
    bm.free()


def skin(name, verts, edges, radii, root=0, levels=2):
    """Smooth organic tubes along a vertex graph (branches, limbs)."""
    obj = mesh_object(name, verts, [], edges)
    obj.modifiers.new("Skin", "SKIN")
    layer = obj.data.skin_vertices[0].data
    for i, r in enumerate(radii):
        layer[i].radius = (r, r)
        layer[i].use_root = i == root
    s = obj.modifiers.new("Subsurf", "SUBSURF")
    s.levels = levels
    s.render_levels = levels
    apply_mods(obj)
    return obj


def extrude_profile(name, pts, width, mat_for_edge=None):
    """Extrudes a closed (x, z) polygon along Y, centered. mat_for_edge(i) gives the
    material index for the side quad between pts[i] and pts[i+1]."""
    n = len(pts)
    hw = width / 2
    verts = [(x, -hw, z) for x, z in pts] + [(x, hw, z) for x, z in pts]
    faces = [list(reversed(range(n))), list(range(n, 2 * n))]
    mats = [0, 0]
    for i in range(n):
        j = (i + 1) % n
        faces.append((i, j, n + j, n + i))
        mats.append(mat_for_edge(i) if mat_for_edge else 0)
    obj = mesh_object(name, verts, faces)
    for poly, mi in zip(obj.data.polygons, mats):
        poly.material_index = mi
    recalc_normals(obj)
    return obj


def set_mats(obj, *mats):
    obj.data.materials.clear()
    for m in mats:
        obj.data.materials.append(m)
    return obj


def smooth(obj, angle=35.0):
    obj.data.shade_smooth()
    if angle < 180:
        obj.data.set_sharp_from_angle(angle=math.radians(angle))
    return obj


def verts_np(obj):
    co = np.empty(len(obj.data.vertices) * 3, np.float32)
    obj.data.vertices.foreach_get("co", co)
    return co.reshape(-1, 3)


def set_verts(obj, co):
    obj.data.vertices.foreach_set("co", co.astype(np.float32).ravel())
    obj.data.update()


def noise3(co, freq, seed, octaves=4):
    """Smooth 3D noise (sum of random plane waves), roughly -1..1."""
    rng = np.random.default_rng(seed)
    total = np.zeros(len(co), np.float32)
    amp, f, norm = 1.0, freq, 0.0
    for _ in range(octaves):
        for _ in range(7):
            d = rng.normal(size=3)
            d /= np.linalg.norm(d)
            total += amp * np.sin(co @ d * f * rng.uniform(0.8, 1.25) + rng.uniform(0, math.tau))
        norm += amp * math.sqrt(7 / 2)
        amp *= 0.5
        f *= 2.1
    return total / norm


def displace(obj, strength, freq, seed, octaves=4, ridged=False):
    co = verts_np(obj)
    nrm = np.empty(len(co) * 3, np.float32)
    obj.data.vertices.foreach_get("normal", nrm)
    nrm = nrm.reshape(-1, 3)
    n = noise3(co, freq, seed, octaves)
    if ridged:
        n = 1.0 - 2.0 * np.abs(n)
    set_verts(obj, co + nrm * (n * strength)[:, None])


# --- UVs ------------------------------------------------------------------------

def uv_layer(obj):
    me = obj.data
    return me.uv_layers.get("UVMap") or me.uv_layers.new(name="UVMap")


def uv_box(obj, tile, grain="x", offset=None):
    """Box projection, `tile` meters per texture repeat. The texture's U runs
    along world axis `grain` wherever the face allows it."""
    me = obj.data
    uv = uv_layer(obj)
    off = offset if offset is not None else (random.random(), random.random())
    g = "xyz".index(grain)
    for p in me.polygons:
        n = p.normal
        ax = max(range(3), key=lambda i: abs(n[i]))
        others = [i for i in range(3) if i != ax]
        if g in others:
            ui, vi = g, next(i for i in others if i != g)
        else:
            ui, vi = others
        for li in p.loop_indices:
            co = me.vertices[me.loops[li].vertex_index].co
            uv.data[li].uv = (co[ui] / tile + off[0], co[vi] / tile + off[1])


def uv_cyl(obj, tile, radius, center=(0.0, 0.0), offset=0.0):
    """Cylindrical projection around Z with a whole number of repeats around,
    so the texture meets itself at the seam. Caps get a flat projection."""
    me = obj.data
    uv = uv_layer(obj)
    repeats = max(1, round(math.tau * radius / tile))
    for p in me.polygons:
        loops = list(p.loop_indices)
        cos = [me.vertices[me.loops[li].vertex_index].co for li in loops]
        if abs(p.normal.z) > 0.75:
            for li, co in zip(loops, cos):
                uv.data[li].uv = (co.x / tile + offset, co.y / tile)
            continue
        us = [(math.atan2(co.y - center[1], co.x - center[0]) / math.tau) * repeats for co in cos]
        if max(us) - min(us) > repeats / 2:
            us = [u + repeats if u < 0 else u for u in us]
        for li, co, u in zip(loops, cos, us):
            uv.data[li].uv = (u + offset, co.z / tile)


def uv_fit_xy(obj):
    """Flat projection of the XY bounds onto 0..1 (coin faces)."""
    me = obj.data
    uv = uv_layer(obj)
    co = verts_np(obj)
    lo, hi = co.min(0), co.max(0)
    span = max(hi[0] - lo[0], hi[1] - lo[1])
    for p in me.polygons:
        for li in p.loop_indices:
            c = me.vertices[me.loops[li].vertex_index].co
            uv.data[li].uv = ((c.x - lo[0]) / span, (c.y - lo[1]) / span)


def uv_card(obj):
    """Each quad gets the full 0..1 square (leaf cards), in vertex order."""
    me = obj.data
    uv = uv_layer(obj)
    corners = [(0, 0), (1, 0), (1, 1), (0, 1)]
    for p in me.polygons:
        for k, li in enumerate(p.loop_indices):
            uv.data[li].uv = corners[k % 4]


# --- assembling -------------------------------------------------------------------

def join(parts, name):
    bpy.ops.object.select_all(action="DESELECT")
    for p in parts:
        p.select_set(True)
    bpy.context.view_layer.objects.active = parts[0]
    if len(parts) > 1:
        bpy.ops.object.join()
    obj = active()
    obj.name = name
    obj.data.name = name
    return obj


def ground_it(obj):
    """Moves the mesh so its bounding box's bottom center is at the origin."""
    co = verts_np(obj)
    lo, hi = co.min(0), co.max(0)
    shift = np.array([-(lo[0] + hi[0]) / 2, -(lo[1] + hi[1]) / 2, -lo[2]], np.float32)
    set_verts(obj, co + shift)
    return obj


def part(obj, mat, uv=None, angle=35.0, **uv_args):
    """Assigns a material, UVs and shading to one piece before it's joined."""
    set_mats(obj, mat)
    if uv == "box":
        uv_box(obj, **uv_args)
    elif uv == "cyl":
        uv_cyl(obj, **uv_args)
    elif uv == "fit":
        uv_fit_xy(obj)
    else:
        uv_box(obj, tile=1.0)
    smooth(obj, angle)
    return obj


