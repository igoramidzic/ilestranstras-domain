def uv_cyl_axis_y(obj, center_xz):
    """Tyre UVs: U around the wheel (tread blocks), V across."""
    me = obj.data
    uv = uv_layer(obj)
    for p in me.polygons:
        loops = list(p.loop_indices)
        cos = [me.vertices[me.loops[li].vertex_index].co for li in loops]
        us = [math.atan2(co.z - center_xz[1], co.x - center_xz[0]) / math.tau for co in cos]
        if max(us) - min(us) > 0.5:
            us = [u + 1 if u < 0 else u for u in us]
        for li, co, u in zip(loops, cos, us):
            uv.data[li].uv = (u * 2, co.y / 0.21)


def gable(w, d, wall_h, roof_h, mat, tile, name="gable"):
    """Triangular wall pieces at both ends (along X) of a pitched roof."""
    pts = [(-d / 2, wall_h), (d / 2, wall_h), (0, wall_h + roof_h)]
    tri = extrude_profile(name, pts, w)
    tri.data.transform(Matrix.Rotation(math.pi / 2, 4, "Z"))
    return part(tri, mat, "box", tile=tile)


def roof(w, d, wall_h, roof_h, overhang, thickness, mat, tile):
    parts = []
    half = d / 2 + overhang
    slope = math.atan2(roof_h, d / 2)
    length = half / math.cos(slope)
    for sy in (-1, 1):
        cy = sy * half / 2
        cz = wall_h + roof_h - (half / 2) * math.tan(slope) + thickness * 0.5
        slab = box((w + overhang * 2, length, thickness), loc=(0, cy, cz), rot=(-sy * slope, 0, 0),
                   bevel_w=0.01)
        parts.append(part(slab, mat, "box", tile=tile, grain="x"))
    ridge = cylinder(0.07, w + overhang * 2, loc=(0, 0, wall_h + roof_h + thickness * 0.7),
                     rot=(0, math.pi / 2, 0), verts=12)
    parts.append(part(ridge, mat, "box", tile=tile))
    return parts


